import argparse
import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))

def parse_args():
    p = argparse.ArgumentParser(description="Evaluate GPU getp output without running CPU logic.")
    p.add_argument("output_txt", help="Path to the output file generated by getp (e.g. ./output.txt)")
    p.add_argument("model", nargs="?", default="dsv2lite", choices=["dsv2lite", "glm47"])
    p.add_argument("-d", "--dir", default=None, help="Dataset directory (default: tests/eval/<model>)")
    p.add_argument("--model-dir", default=None, help="Path to HF model dir (required for --fuzzy if not in reference.json)")
    p.add_argument("--fuzzy", action="store_true", help="Run METEOR and BERTScore evaluation (like free-run in eval.py)")
    p.add_argument("--thresholds", default=os.path.join(_HERE, "threshold.json"))
    return p.parse_args()

def read_id_lines(path):
    with open(path) as f:
        return [[int(x) for x in ln.split()] for ln in f if ln.strip()]

def main():
    args = parse_args()
    
    if not os.path.exists(args.output_txt):
        sys.exit(f"Output file not found: {args.output_txt}")
        
    data = args.dir or os.path.join(_HERE, args.model)
    comps_path = os.path.join(data, "completions.i32.txt")
    
    if not os.path.exists(comps_path):
        sys.exit(f"Golden completions not found: {comps_path}")
        
    ref = json.load(open(os.path.join(data, "reference.json")))
    recs = ref["requests"]
    
    comps = read_id_lines(comps_path)
    preds_ids = read_id_lines(args.output_txt)
    # print(len(comps), "comps: ", comps)
    # print()
    # print(len(preds_ids), "preds_ids: ", preds_ids)
    
    if len(comps) != len(preds_ids):
        print(f"Warning: Expected {len(comps)} requests, but found {len(preds_ids)} in {args.output_txt}")
        
    n = min(len(comps), len(preds_ids))
    
    # 1. Đánh giá tính khớp mã thông báo (Exact/Token-level Match)
    # Vì getp là greedy free-run, chúng ta có thể so sánh trực tiếp token sinh ra với golden tokens
    total_tokens = 0
    match_tokens = 0
    exact_seq_matches = 0
    
    for i in range(n):
        gold = comps[i]
        pred = preds_ids[i]
        
        # getp có thể sinh nhiều hoặc ít hơn số token reference (phụ thuộc vào max_steps hoặc EOS)
        # So sánh trên phần ngắn nhất giữa cả hai (nếu pred ngắn hơn gold, sẽ bị phạt phần sau)
        compare_len = min(len(gold), len(pred))
        
        req_match = 0
        for j in range(compare_len):
            if gold[j] == pred[j]:
                req_match += 1
                
        # Coi như khớp sequence nếu tiền tố khớp hoàn toàn với độ dài của gold reference
        if req_match == len(gold):
            exact_seq_matches += 1
            
        match_tokens += req_match
        total_tokens += len(gold)
        
    seq_acc = exact_seq_matches / n * 100 if n > 0 else 0
    tok_acc = match_tokens / total_tokens * 100 if total_tokens > 0 else 0
    
    print(f"[{args.model}] Evaluated {n} requests from {args.output_txt}")
    print(f"  Free-run Sequence Prefix Match: {seq_acc:.2f}% ({exact_seq_matches}/{n})")
    print(f"  Free-run Token-Level Accuracy : {tok_acc:.2f}% ({match_tokens}/{total_tokens})")
    
    # 2. Đánh giá Fuzzy (METEOR, BERTScore) giống hệt eval.py 
    if args.fuzzy:
        model_dir = args.model_dir or ref.get("model_dir")
        if not model_dir or not os.path.exists(model_dir):
            sys.exit("Error: --model-dir must be provided and valid for --fuzzy evaluation.")
            
        print("\nRunning fuzzy evaluation (METEOR, BERTScore)...")
        # Chỉ nạp khi thực sự cần thiết vì thư viện này khá nặng
        from transformers import AutoTokenizer
        import evaluate
        
        tok = AutoTokenizer.from_pretrained(model_dir, trust_remote_code=True)
        preds_text, refs_text = [], []
        
        for i in range(n):
            preds_text.append(tok.decode(preds_ids[i]))
            refs_text.append(tok.decode(comps[i]))
            
        meteor_score = evaluate.load("meteor").compute(predictions=preds_text, references=refs_text)["meteor"]
        bs = evaluate.load("bertscore").compute(predictions=preds_text, references=refs_text, lang="en")
        f1 = sum(bs["f1"]) / len(bs["f1"])
        
        thr = json.load(open(args.thresholds))
        
        print(f"  METEOR       = {meteor_score:.4f}  (ngưỡng/threshold: {thr['meteor']})")
        print(f"  BERTScore-F1 = {f1:.4f}  (ngưỡng/threshold: {thr['bertscore_f1']})")
        
        ok = meteor_score >= thr["meteor"] and f1 >= thr["bertscore_f1"]
        print("\n  RESULT:", "ok" if ok else "FAIL")
        sys.exit(0 if ok else 1)

if __name__ == "__main__":
    main()
